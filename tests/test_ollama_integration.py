"""Integration tests verifying real local Ollama inference against VehicleGPT database.

Executes all three primary demonstration questions through the FastAPI endpoint
and verifies that local Ollama (llama3.2:3b) generates grounded answers conforming
to the underlying SQLite database telemetry and analytics.
"""

import pytest
from fastapi.testclient import TestClient

from app.services.llm_service import ollama_service


@pytest.fixture(scope="module")
def require_local_ollama():
    """Skip suite if local Ollama daemon or model is not running."""
    available, error = ollama_service.is_available()
    if not available:
        pytest.skip(f"Local Ollama is not available: {error}")


def test_real_model_demo_query_1_adas_disengagements(client: TestClient, require_local_ollama):
    """Demo Query 1: ADAS Disengagements across 30-day timeline.

    Verifies model explanation grounds in 17 disengagement events and categorized triggers.
    """
    question = "Analyze recent ADAS disengagements across the 30-day timeline and summarize common triggers."
    response = client.post("/api/query", json={"question": question})
    assert response.status_code == 200

    data = response.json()
    assert data["question"] == question
    assert data["intent"] == "adas_disengagement_analysis"
    assert "events" in data["sources"]

    # Underlying database facts
    evidence = data["data"]
    assert evidence["total_disengagements"] == 17
    assert len(evidence["common_triggers_breakdown"]) >= 3

    # Answer generated by model
    answer = data["answer"]
    assert len(answer) > 50
    # Model should mention disengagements and recognized triggers from the evidence
    answer_lower = answer.lower()
    assert any(term in answer_lower for term in ["disengagement", "17", "steering", "sun glare", "camera"])
    assert any("Ollama" in w for w in data["warnings"])


def test_real_model_demo_query_2_energy_efficiency(client: TestClient, require_local_ollama):
    """Demo Query 2: City vs Highway Energy Efficiency and Regeneration.

    Verifies model grounds in 15.2 kWh/100 km (city) vs 20.78 kWh/100 km (highway).
    """
    question = "Compare City versus Highway energy consumption metrics in kWh/100 km and regeneration performance."
    response = client.post("/api/query", json={"question": question})
    assert response.status_code == 200

    data = response.json()
    assert data["question"] == question
    assert data["intent"] == "energy_efficiency"
    assert "trips" in data["sources"]
    assert "telemetry" in data["sources"]

    # Underlying database facts
    evidence = data["data"]
    comp = evidence["comparison"]
    assert comp["city_kwh_per_100km"] == 15.2
    assert comp["highway_kwh_per_100km"] == 20.78
    assert comp["more_efficient_mode"] == "city"

    # Answer generated by model
    answer = data["answer"]
    assert len(answer) > 50
    answer_lower = answer.lower()
    # Check that model cites the metrics accurately from evidence
    assert "city" in answer_lower
    assert "highway" in answer_lower
    assert any(num in answer for num in ["15.2", "20.78", "20.8", "28", "36.7"])
    assert any("Ollama" in w for w in data["warnings"])


def test_real_model_demo_query_3_battery_overheating(client: TestClient, require_local_ollama):
    """Demo Query 3: Battery Overheating Anomaly Timeline.

    Verifies model grounds in 58.6°C peak, liquid chiller pump response, and 34.0°C resolution.
    """
    question = "Investigate the battery overheating incident and describe telemetry changes before and after the warning."
    response = client.post("/api/query", json={"question": question})
    assert response.status_code == 200

    data = response.json()
    assert data["question"] == question
    assert data["intent"] == "thermal_anomaly_investigation"
    assert "events" in data["sources"]
    assert "telemetry" in data["sources"]

    # Underlying database facts
    evidence = data["data"]
    incident = evidence["incident_event"]
    assert incident["id"] == "ev-synth-overheat-001"
    assert incident["safety_threshold_celsius"] == 55.0
    assert 58.0 <= incident["peak_temperature_celsius"] <= 59.0
    assert 34.0 <= evidence["post_warning_telemetry"]["final_stabilized_temperature_celsius"] <= 35.0

    # Answer generated by model
    answer = data["answer"]
    assert len(answer) > 50
    answer_lower = answer.lower()
    # Check that model describes the thermal event and countermeasures accurately
    assert any(term in answer_lower for term in ["58.6", "temperature", "chiller", "cooling", "34"])
    assert any("Ollama" in w for w in data["warnings"])
